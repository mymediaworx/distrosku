<?php
/**
 * Vega ERP one-time UPGRADE runner (phase __PHASE__). Deletes itself after a successful run.
 * Visit: https://vegatest1.distrosku.com/upgrade-__TOKEN__.php?token=__TOKEN__
 * Keeps the existing laravel/.env and laravel/storage untouched.
 */
declare(strict_types=1);
@ini_set('display_errors', '0');
error_reporting(0);
@set_time_limit(300);

const UPGRADE_TOKEN = '__TOKEN__';
const UPGRADE_PHASE = '__PHASE__';
const UPGRADE_SEEDERS = [__SEEDERS__];
$base = realpath(__DIR__.'/../laravel');

function h($s): string { return htmlspecialchars((string) $s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'); }

if (! isset($_GET['token']) || ! is_string($_GET['token']) || ! hash_equals(UPGRADE_TOKEN, $_GET['token'])) {
    http_response_code(404);
    exit('Not found');
}

$log = [];
$errors = [];
$done = false;
$deleted = false;

if ($base === false || ! is_file($base.'/vendor/autoload.php')) {
    $errors[] = 'Laravel app not found at ../laravel.';
} elseif (! is_file($base.'/.env')) {
    $errors[] = 'laravel/.env is missing. This is an UPGRADE for an existing install; restore .env (or use the setup script for a new install).';
}

$secretSaved = null;
if (! $errors && $_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['deploy_secret']) && trim((string) $_POST['deploy_secret']) !== '') {
    // Shared HMAC secret for public_html/deploy.php, stored OUTSIDE the web root (laravel/.deploy-secret, mode 600).
    $sec = trim((string) $_POST['deploy_secret']);
    if (! preg_match('/^[A-Za-z0-9_\-]{32,128}$/', $sec)) {
        $errors[] = 'Deploy secret must be 32-128 letters/digits (as generated by the box).';
    } else {
        $old = umask(0077);
        $secretSaved = @file_put_contents($base.'/.deploy-secret', $sec."\n") !== false;
        umask($old);
        @chmod($base.'/.deploy-secret', 0600);
        if ($secretSaved) {
            $log[] = 'Saved deploy secret to laravel/.deploy-secret (mode 600).';
        } else {
            $errors[] = 'Could not write laravel/.deploy-secret.';
        }
    }
}

if (! $errors && $_SERVER['REQUEST_METHOD'] === 'POST') {
    try {
        // Package manifest and config/route caches are stale after new code/vendor (new packages added). Remove before boot.
        foreach (glob($base.'/bootstrap/cache/*.php') ?: [] as $f) {
            @unlink($f);
        }
        $log[] = 'Cleared bootstrap/cache (package manifest, config, routes).';

        require $base.'/vendor/autoload.php';
        $app = require $base.'/bootstrap/app.php';
        $kernel = $app->make(Illuminate\Contracts\Console\Kernel::class);
        $kernel->bootstrap();

        $run = function (string $cmd, array $args = []) use ($kernel, &$log) {
            $code = $kernel->call($cmd, $args);
            $out = trim($kernel->output());
            $log[] = '$ php artisan '.$cmd.' (exit '.$code.')'.($out !== '' ? "\n".$out : '');
            if ($code !== 0) {
                throw new RuntimeException('Command failed: '.$cmd);
            }
        };

        $run('down', ['--retry' => 30]);
        try {
            $run('migrate', ['--force' => true]);
            // All idempotent upgrade seeders, generated per phase by build-upgrade.sh (UPGRADE_SEEDERS).
            foreach (UPGRADE_SEEDERS as $seeder) {
                $run('db:seed', ['--class' => 'Database\\Seeders\\'.$seeder, '--force' => true]);
            }
            if (! file_exists(__DIR__.'/storage')) { // public disk link for uploaded images (public_html/storage)
                $run('storage:link');
            }
            $run('optimize:clear');
            $run('config:cache');
            $run('route:cache');
            $run('view:cache');
        } finally {
            $run('up');
        }
        foreach (['storage', 'bootstrap/cache'] as $dir) {
            @chmod($base.'/'.$dir, 0775);
        }
        $done = true;
    } catch (Throwable $e) {
        $errors[] = 'Upgrade stopped: '.$e->getMessage();
    }
    if ($done && getenv('VEGA_KEEP_UPGRADE') !== '1') {
        $deleted = @unlink(__FILE__);
    }
}
?><!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex,nofollow"><title>Vega ERP upgrade</title>
<style>body{font-family:system-ui,sans-serif;max-width:680px;margin:2rem auto;padding:0 1rem}button{padding:.7rem 1.4rem}pre{background:#111;color:#eee;padding:1rem;white-space:pre-wrap;font-size:.8rem}.err{color:#b00}.ok{color:#070}</style></head><body>
<h1>Vega ERP upgrade (phase __PHASE__)</h1>
<p>Seeders that will run: <?= h(implode(', ', UPGRADE_SEEDERS)) ?></p>
<?php foreach ($errors as $e) { ?><p class="err"><?= h($e) ?></p><?php } ?>
<?php if ($log) { ?><h2>Log</h2><pre><?= h(implode("\n", $log)) ?></pre><?php } ?>
<?php if ($done) { ?>
  <p class="ok"><strong>Upgrade complete.</strong> <a href="/admin">Go to /admin</a></p>
  <p><?= $deleted ? 'This upgrade file has deleted itself.' : '<strong class="err">Could not delete this file. Delete it now in File Manager.</strong>' ?></p>
<?php } elseif (! $errors) { ?>
  <p>This will put the site in maintenance mode briefly, run database migrations, add the KY tax rate rows, and rebuild caches. Your <code>.env</code> and <code>storage/</code> are not touched.</p>
  <form method="post" action="?token=<?= h(UPGRADE_TOKEN) ?>">
    <p><label>Deploy secret (optional: paste the value from the box file secrets/deploy_hmac_secret to enable one-command deploys via deploy.php)<br>
      <input type="password" name="deploy_secret" autocomplete="off" style="width:100%;padding:.5rem" minlength="32" maxlength="128"></label></p>
    <button type="submit">Run upgrade</button></form>
<?php } ?>
</body></html>
